const assert = require("node:assert/strict");
const mongoose = require("mongoose");
const Request = require("../../../models/MaintenanceRequest");
const Outreach = require("../../../models/VendorOutreach");
const Completion = require("../../../models/JobCompletion");
const Analysis = require("../../../models/QuoteAnalysis");
const ctrl = require("../../../controllers/quoteReview.controller");
const key = new mongoose.Types.ObjectId().toString();
let related = 0;
const query = rows => ({ select() { return this; }, sort() { return this; }, lean: async () => structuredClone(rows) });
Request.findOne = filter => query(filter.landlordId === "owner" ? { _id: key } : null);
Outreach.find = scope => { assert.equal(scope.landlordId, "owner"); related++; return query([]); };
Completion.find = scope => { assert.equal(scope.landlordId, "owner"); related++; return query([]); };
Analysis.find = scope => { assert.equal(scope.landlordId, "owner"); related++; return query([]); };
require("../../../models/QuoteClarification").find = scope => { assert.equal(scope.landlordId, "owner"); related++; return query([]); };
require("../../../models/ApprovalRequest").find = scope => { assert.equal(scope.landlordId, "owner"); assert.equal(scope.status, "rejected"); related++; return query([]); };
const res = () => ({ statusCode: 200, status(value) { this.statusCode = value; return this; }, json(value) { this.body = value; return this; } });
async function main() {
  let output = res();
  await ctrl.getReviews({ user: { id: "owner", role: "tenant" }, params: { id: key } }, output);
  assert.equal(output.statusCode, 403); assert.equal(related, 0);
  output = res();
  await ctrl.getReviews({ user: { id: "other", role: "landlord" }, params: { id: key } }, output);
  assert.equal(output.statusCode, 404); assert.equal(related, 0);
  output = res();
  await ctrl.getReviews({ user: { id: "owner", role: "landlord" }, params: { id: key } }, output);
  assert.equal(output.statusCode, 200); assert.equal(related, 5);
  assert.deepEqual(output.body.data, { quotes: [], invoices: [] });
  const visible = ctrl.presentAnalysis({ status: "ready", source: "development_stub", result: { summary: "Simulation" }, leaseToken: "PRIVATE" });
  assert.equal(visible.simulated, true); assert(!JSON.stringify(visible).includes("PRIVATE"));
  assert.equal(ctrl.presentAnalysis({ status: "running", leaseUntil: new Date(0) }).status, "unavailable");
  output = res();
  await ctrl.reopenReview({ user: { id: "owner", role: "tenant" }, params: { id: key } }, output);
  assert.equal(output.statusCode, 403);
  output = res();
  await ctrl.reopenReview({ user: { id: "owner", role: "landlord" }, params: { id: key, stage: "invoice", subjectId: key }, body: {} }, output);
  assert.equal(output.statusCode, 400); assert.equal(output.body.code, "invalid_reopen_input");
  console.log("Cost review projection: current ownership, role, safe simulation and expired execution states PASS");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
